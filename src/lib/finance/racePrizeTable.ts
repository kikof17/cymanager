export function getIndividualRacePrizeBase(
  division: DivisionLevel,
  position: string | number
): number | null {
  const positionNumber = typeof position === "number"
    ? position
    : Number.parseInt(String(position).replace(/[^\d]/g, ""), 10);

  if (Number.isNaN(positionNumber)) {
    return null;
  }

  const values = INDIVIDUAL_RACE_PRIZES[positionNumber];

  if (!values) {
    return null;
  }

  const divisionIndex = Number.parseInt(division.replace("D", ""), 10) - 1;

  if (Number.isNaN(divisionIndex) || divisionIndex < 0 || divisionIndex > 8) {
    return null;
  }

  return values[divisionIndex] ?? null;
}

export function getIndividualRacePrizeMultiplier(courseTitle: string): number {
  const normalized = courseTitle
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

  return normalized.includes("etape") || normalized.includes("c2") ? 0.5 : 1;
}

function roundUpToNextThousand(value: number): number {
  return Math.ceil(value / 1000) * 1000;
}

export function getProRacePrize(
  division: DivisionLevel,
  position: string | number,
  courseTitle: string
): number | null {
  const basePrize = getIndividualRacePrizeBase(division, position);

  if (basePrize === null) {
    return null;
  }

  return roundUpToNextThousand(
    basePrize * getIndividualRacePrizeMultiplier(courseTitle)
  );
}